
#' Render an automated analysis as a self-contained HTML report
#'
#' Produces a light-theme, dependency-free HTML report with result cards,
#' diagnostic badges, a CSS forest plot for the model coefficients and the
#' full decision log. No external stylesheet, script or network access is
#' needed, so the file can be opened offline or attached to a manuscript.
#'
#' @details
#' Purpose: turn the structured result bundle from [mc_auto_analyze()] into a
#' readable report without introducing rmarkdown, knitr or HTML dependencies.
#' All tables are HTML-escaped; numeric values are rounded for display only,
#' while the original precision remains in the `mc_auto_analysis` object.
#'
#' @param x An object of class `mc_auto_analysis`.
#' @param file Output path. Parent directories are created if needed.
#' @param title Report title.
#' @param max_rows Maximum rows rendered per table; default `30`.
#' @param quiet Suppress the message naming the written file; default `FALSE`.
#' @return Invisibly returns the output file path.
#' @examples
#' # SIMULATED DATA -- 3000 synthetic hypertension-trial subjects.
#' # Not real patients; see ?sim_htn_trial before interpreting any result.
#' data(sim_htn_trial)
#' d <- sim_htn_trial
#' r <- mc_auto_analyze(d, outcome = "bp_control",
#'   vars = c("age", "bmi", "sbp_baseline", "ldl", "smoke"), auc_boot = 0L)
#' mc_auto_report(r, file = tempfile(fileext = ".html"), quiet = TRUE)
#' @export
mc_auto_report <- function(x, file = "macodgent-auto-report.html",
                           title = "macodgent automated analysis",
                           max_rows = 30L, quiet = FALSE) {
  if (!inherits(x, "mc_auto_analysis"))
    stop("`x` must be an object from mc_auto_analyze().")
  dir <- dirname(file)
  if (!dir.exists(dir)) dir.create(dir, recursive = TRUE, showWarnings = FALSE)

  ov <- x$overview
  kpi <- function(v, lab) paste0('<div class="kpi"><b>', .mc_esc(v),
                                 '</b><span>', .mc_esc(lab), "</span></div>")
  kpis <- paste0(
    kpi(ov$n_rows, "rows"), kpi(ov$n_cols, "columns"),
    kpi(ov$n_complete_rows, "complete rows"),
    kpi(ov$n_predictors, "eligible predictors"),
    kpi(ov$n_in_model, "predictors in model"),
    kpi(toupper(ov$analysis), "model family"), sep = "")

  findings <- paste0('<ul class="findings">',
                     paste0("<li>", .mc_esc(x$findings), "</li>",
                            collapse = ""), "</ul>")
  warn_html <- if (length(x$warnings))
    paste0('<div class="warn"><b>Caveats</b><br>',
           paste(.mc_esc(x$warnings), collapse = "<br>"), "</div>") else ""

  parts <- c(
    .mc_card("Key findings", paste0(findings, warn_html), wide = TRUE),
    .mc_card("Column audit", .mc_html_table(x$columns, max_rows), wide = TRUE),
    .mc_card("Descriptive statistics",
             .mc_html_table(x$descriptives, max_rows), wide = TRUE),
    .mc_card("Baseline table", .mc_html_table(x$baseline, max_rows)),
    .mc_card("Group comparison", .mc_html_table(x$comparison, max_rows)),
    .mc_card("Correlation", .mc_html_table(x$correlation, max_rows)),
    .mc_card("Univariable screening",
             .mc_html_table(x$screening, max_rows)))

  if (!is.null(x$model)) {
    co <- x$model$coefficients
    eff <- if (!is.null(co)) co$effect[1] else "Beta"
    forest <- if (!is.null(co)) .mc_forest(co, eff) else ""
    parts <- c(parts,
               .mc_card(paste0("Multivariable model: ", x$model$formula),
                        paste0(forest, '<p class="empty">Effect scale: ',
                               .mc_esc(eff), "; filled markers indicate p < ",
                               .mc_esc(ov$alpha), ".</p>",
                               .mc_html_table(co, max_rows)), wide = TRUE),
               .mc_card("Model diagnostics",
                        .mc_checks_html(x$model$checks), wide = TRUE),
               .mc_card("Model performance",
                        .mc_html_table(x$model$performance, max_rows)))
  }

  parts <- c(parts,
             .mc_card("Decision log", .mc_html_table(x$decisions, max_rows),
                      wide = TRUE))

  html <- paste0(
    "<!DOCTYPE html><html lang=\"en\"><head><meta charset=\"utf-8\">",
    "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">",
    "<title>", .mc_esc(title), "</title><style>", .mc_css,
    "</style></head><body><div class=\"wrap\"><header><h1>",
    .mc_esc(title), "</h1><p class=\"sub\">", .mc_esc(ov$generated),
    " &middot; ", .mc_esc(ov$p_adjust), " adjustment &middot; alpha ",
    .mc_esc(ov$alpha), "</p></header><div class=\"kpis\">", kpis,
    '</div><div class="grid">', paste(parts, collapse = ""),
    "</div><footer>Generated by macodgent. Automated test selection and ",
    "variable pre-selection are exploratory; verify choices against the ",
    "clinical analysis plan and inspect the raw distributions before ",
    "reporting.</footer></div>",
    "<script>(function(){document.querySelectorAll('table').forEach(function(t){",
    "var h=t.querySelectorAll('thead th');if(!h.length)return;",
    "for(var j=0;j<h.length;j++){(function(th,col){th.className+=' sortable';",
    "th.addEventListener('click',function(){var b=t.tBodies[0];if(!b)return;",
    "var rows=[].slice.call(b.rows);var asc=th.getAttribute('data-asc')!=='1';",
    "th.setAttribute('data-asc',asc?'1':'0');",
    "rows.sort(function(a,c){var x=a.cells[col],y=c.cells[col];",
    "if(!x||!y)return 0;var sx=x.textContent.trim(),sy=y.textContent.trim();",
    "var vx=parseFloat(sx.replace(/[^0-9.-]/g,'')),vy=parseFloat(sy.replace(/[^0-9.-]/g,''));",
    "var r=(!isNaN(vx)&&!isNaN(vy))?(vx-vy):sx.localeCompare(sy);",
    "return asc?r:-r;});rows.forEach(function(r){b.appendChild(r);});});",
    "})(h[j],j);}});})();</script></body></html>")

  writeLines(html, con = file, useBytes = TRUE)
  if (!quiet) cat("HTML report written to: ", normalizePath(file), "\n", sep = "")
  invisible(file)
}

#' Export an automated analysis to CSV tables and an RDS file
#'
#' Writes every tabular component of an [mc_auto_analyze()] result into one
#' directory, so the results can be shared with collaborators, opened in a
#' spreadsheet, or version-controlled alongside a manuscript. The complete R
#' object is saved as `analysis.rds` for exact reproducibility.
#'
#' @details
#' Purpose: make the one-call result bundle portable without a report generator.
#' Only non-empty tables are written; the original R object retains full
#' numeric precision, while the CSV files are convenience copies.
#'
#' @param x An object of class `mc_auto_analysis`.
#' @param dir Output directory, created if it does not exist.
#' @param rds Also save the complete object as `analysis.rds`; default `TRUE`.
#' @param word Also write `report.doc`, an HTML-table document that opens
#'   directly in Word / WPS without extra R packages; default `FALSE`.
#' @param quiet Suppress the message naming the output directory;
#'   default `FALSE`.
#' @return Invisibly returns the vector of written file paths.
#' @examples
#' # SIMULATED DATA -- 3000 synthetic hypertension-trial subjects.
#' # Not real patients; see ?sim_htn_trial before interpreting any result.
#' data(sim_htn_trial)
#' d <- sim_htn_trial
#' r <- mc_auto_analyze(d, outcome = "sbp_week12",
#'   vars = c("age", "bmi", "sbp_baseline", "ldl"), auc_boot = 0L)
#' mc_auto_export(r, dir = tempfile(), word = TRUE, quiet = TRUE)
#' @export
mc_auto_export <- function(x, dir = "macodgent-output", rds = TRUE,
                           word = FALSE, quiet = FALSE) {
  if (!inherits(x, "mc_auto_analysis"))
    stop("`x` must be an object from mc_auto_analyze().")
  if (!dir.exists(dir)) dir.create(dir, recursive = TRUE, showWarnings = FALSE)
  tabs <- list(
    overview = x$overview, columns = x$columns,
    descriptives = x$descriptives, baseline = x$baseline,
    comparison = x$comparison, correlation = x$correlation,
    screening = x$screening, decisions = x$decisions,
    findings = data.frame(finding = x$findings, stringsAsFactors = FALSE),
    warnings = if (length(x$warnings))
      data.frame(warning = x$warnings, stringsAsFactors = FALSE) else NULL)
  if (!is.null(x$model)) {
    tabs$model_coefficients <- x$model$coefficients
    tabs$model_checks <- x$model$checks
    tabs$model_performance <- x$model$performance
  }
  paths <- character(0)
  for (nm in names(tabs)) {
    d <- tabs[[nm]]
    if (is.null(d) || !is.data.frame(d) || nrow(d) == 0L) next
    p <- file.path(dir, paste0(nm, ".csv"))
    utils::write.csv(d, file = p, row.names = FALSE, na = "")
    paths <- c(paths, p)
  }
  if (rds) {
    p <- file.path(dir, "analysis.rds")
    saveRDS(x, p)
    paths <- c(paths, p)
  }
  if (isTRUE(word)) {
    ## Word / WPS opens HTML tables natively; this avoids officer / rmarkdown.
    blocks <- c(
      "<html><head><meta charset='utf-8'><style>",
      "body{font-family:Calibri,Arial;font-size:11pt;color:#1b2330}",
      "h2{font-size:14pt;border-bottom:1px solid #ccc;padding-bottom:4px}",
      "table{border-collapse:collapse;width:100%;margin-bottom:18px}",
      "th,td{border:1px solid #bbb;padding:4px 6px;text-align:left;font-size:10pt}",
      "th{background:#eef1f6}</style></head><body>",
      paste0("<h1>", .mc_esc("macodgent automated analysis"), "</h1>"))
    for (nm in names(tabs)) {
      d <- tabs[[nm]]
      if (is.null(d) || !is.data.frame(d) || nrow(d) == 0L) next
      blocks <- c(blocks, paste0("<h2>", .mc_esc(nm), "</h2>"),
                  .mc_html_table(d, 1000L))
    }
    blocks <- c(blocks, "</body></html>")
    p <- file.path(dir, "report.doc")
    writeLines(paste(blocks, collapse = "\n"), con = p, useBytes = TRUE)
    paths <- c(paths, p)
  }
  if (!quiet)
    cat(length(paths), " file(s) written to ", normalizePath(dir), "\n",
        sep = "")
  invisible(paths)
}
